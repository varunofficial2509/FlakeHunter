// Shared by every Java module: Java 21 toolchain, compiler settings, JUnit Platform.
plugins {
    java
}

group = "dev.flakehunter"
version = "0.0.1-SNAPSHOT"

java {
    toolchain {
        languageVersion = JavaLanguageVersion.of(21)
    }
}

